package com.enterprise.llm.rag.guard;

import com.enterprise.llm.rag.model.SearchResult;
import org.slf4j.Logger;
import org.slf4j.LoggerFactory;
import org.springframework.beans.factory.annotation.Value;
import org.springframework.stereotype.Service;

import java.util.*;
import java.util.regex.Matcher;
import java.util.regex.Pattern;

/**
 * Enterprise RAG Groundedness & Hallucination Guardrail.
 * Evaluates generated answer claims against retrieved knowledge chunks.
 * Detects unsupported factual claims and applies policy actions (PASS, WARN_APPEND, REJECT_FALLBACK).
 */
@Service
public class RagFaithfulnessEvaluator {

    private static final Logger log = LoggerFactory.getLogger(RagFaithfulnessEvaluator.class);

    private static final Pattern SENTENCE_SPLIT_PATTERN = Pattern.compile("(?<=[。！？\\n.!?])\\s*");
    private static final Pattern NUMERIC_PATTERN = Pattern.compile("\\d+(?:[.\\d]+)?(?:元|天|年|月|万|人|折|%|倍|个|次|kg|km)?");
    private static final Set<String> STOP_WORDS = Set.of(
            "根据", "以及", "此外", "公司", "企业", "可以", "如果", "进行", "提供", "对于",
            "关于", "因为", "所以", "并且", "这个", "那个", "这些", "那些", "部分", "相关"
    );

    private final double passThreshold;
    private final double warnThreshold;

    public RagFaithfulnessEvaluator(
            @Value("${rag.guardrail.pass-threshold:0.65}") double passThreshold,
            @Value("${rag.guardrail.warn-threshold:0.40}") double warnThreshold
    ) {
        this.passThreshold = passThreshold;
        this.warnThreshold = warnThreshold;
    }

    public RagFaithfulnessEvaluator() {
        this(0.65, 0.40);
    }

    /**
     * Evaluates whether the generated response is faithful to the retrieved RAG chunks.
     *
     * @param chunks the retrieved context chunks
     * @param answer the response generated by the LLM
     * @return evaluation result with groundedness score and safety recommendation
     */
    public FaithfulnessResult evaluate(List<SearchResult> chunks, String answer) {
        if (chunks == null || chunks.isEmpty()) {
            return FaithfulnessResult.pass(0.0, answer, 0, 0, "No RAG context chunks provided for verification");
        }
        if (answer == null || answer.isBlank()) {
            return FaithfulnessResult.pass(1.0, "", 0, 0, "Empty answer");
        }

        StringBuilder contextBuilder = new StringBuilder();
        for (SearchResult r : chunks) {
            if (r != null && r.content() != null) {
                contextBuilder.append(r.content().toLowerCase()).append(" ");
            }
        }
        String contextCorpus = contextBuilder.toString();

        String[] rawSentences = SENTENCE_SPLIT_PATTERN.split(answer);
        List<String> claims = new ArrayList<>();
        for (String s : rawSentences) {
            String trimmed = s.trim();
            if (trimmed.length() >= 6) { // Filter out greetings or trivial statements
                claims.add(trimmed);
            }
        }

        if (claims.isEmpty()) {
            return FaithfulnessResult.pass(1.0, answer, 0, 0, "No substantive factual claims to verify");
        }

        int supportedClaims = 0;
        int evaluatedClaims = 0;

        for (String claim : claims) {
            Set<String> salientTokens = extractSalientTokens(claim);
            if (salientTokens.isEmpty()) {
                continue;
            }

            evaluatedClaims++;
            int matched = 0;
            for (String token : salientTokens) {
                if (contextCorpus.contains(token.toLowerCase())) {
                    matched++;
                }
            }

            double matchRatio = (double) matched / salientTokens.size();
            // A claim is supported if >= 50% of its salient facts/entities exist in the context corpus
            if (matchRatio >= 0.50) {
                supportedClaims++;
            }
        }

        int totalToUse = Math.max(1, evaluatedClaims);
        double score = (double) supportedClaims / totalToUse;
        score = Math.round(score * 100.0) / 100.0;

        String reasoning = String.format("Grounded %d/%d substantive claims against %d knowledge chunks (score=%.2f)",
                supportedClaims, totalToUse, chunks.size(), score);

        log.debug("RAG Faithfulness evaluation: {}", reasoning);

        if (score >= passThreshold) {
            return FaithfulnessResult.pass(score, answer, totalToUse, supportedClaims, reasoning);
        } else if (score >= warnThreshold) {
            return FaithfulnessResult.warn(score, answer, totalToUse, supportedClaims, reasoning);
        } else {
            return FaithfulnessResult.fallback(score, totalToUse, supportedClaims, reasoning);
        }
    }

    private Set<String> extractSalientTokens(String text) {
        Set<String> tokens = new HashSet<>();

        // 1. Extract numbers and numeric metrics
        Matcher numMatcher = NUMERIC_PATTERN.matcher(text);
        while (numMatcher.find()) {
            String match = numMatcher.group().trim();
            if (!match.isEmpty()) {
                tokens.add(match);
            }
        }

        // 2. Extract Chinese Bi-Grams and English words
        String cleaned = text.replaceAll("[^\\p{IsHan}a-zA-Z0-9]", " ");
        String[] words = cleaned.split("\\s+");
        for (String word : words) {
            if (word.isBlank() || STOP_WORDS.contains(word)) {
                continue;
            }
            if (word.matches("[a-zA-Z0-9_-]{2,}")) {
                tokens.add(word);
            } else if (word.matches("[\\p{IsHan}]+")) {
                // Chinese character sequence: extract 2-grams
                for (int i = 0; i < word.length() - 1; i++) {
                    String biGram = word.substring(i, i + 2);
                    if (!STOP_WORDS.contains(biGram)) {
                        tokens.add(biGram);
                    }
                }
            }
        }

        return tokens;
    }
}
